# 2-7 Stripping Names
nama = "\t\n Yusrina Putri Rahmawati \n\t"

print("Nama asli (whitespace ikut tampil):")
print(nama)

print("Setelah lstrip() (hapus di kiri):")
print(nama.lstrip())

print("Setelah rstrip() (hapus di kanan):")
print(nama.rstrip())

print("Setelah strip() (hapus di kiri dan kanan):")
print(nama.strip())