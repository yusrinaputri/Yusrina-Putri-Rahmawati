# Pakai list program 4-1
pizzas = ['pepperoni', 'margherita', 'sosis', 'keju', 'jamur', 'daging asap', 'hawaiian']

# Tiga item pertama
print("Tiga item pertama dalam list adalah:")
print(pizzas[:3])

# Tiga item dari tengah list
print("\nTiga item dari tengah list adalah:")
print(pizzas[2:5])

# Tiga item terakhir
print("\nTiga item terakhir dalam list adalah:")
print(pizzas[-3:])