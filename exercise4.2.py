# Menyimpan hewan-hewan yang sama-sama bisa menjadi hewan peliharaan
hewan = ['kucing', 'anjing', 'kelinci']

# Mencetak nama setiap hewan
for h in hewan:
    print(h)
    

# Pernyataan tentang setiap hewan
for h in hewan:
    print(f"Seekor {h} akan menjadi hewan peliharaan yang baik dan lucu.")

# Di luar loop: kesamaan semua hewan tersebut
print("\nSemua hewan di daftar ini akan menjadi hewan peliharaan yang baik dan lucu!")